import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const input = process.argv[2];
if (!input) throw new Error('Informe a pasta dos snapshots oficiais revisados.');
const hash = value => createHash('sha256').update(value).digest('hex');
const read = name => readFileSync(resolve(input, name));
const source = read('svrs-classification.source.json');
const normalized = read('svrs-nfse-classifications.all-validities.json');
const creditHtml = read('svrs-credit.html');
const creditSource = read('svrs-presumed-credits.all-validities.json');
assert.equal(hash(source), '0bc584c60039708f62a7240201352924da5d6c94fd92761d89dc0fefbe77f41c');
assert.equal(hash(creditHtml), '7a5d0ef054337af425d60a78ac197f9680a10db41931240219a335f63a006f96');
assert.equal(hash(creditSource), 'f32d99b1dddcb2ae3dcef65afcc9759b637dc60cb1aa70ed33035d9731c5e30d');
const upstream = JSON.parse(source);
const classes = JSON.parse(normalized).sort((a, b) => a.classificationCode.localeCompare(b.classificationCode));
const credits = JSON.parse(creditSource);
assert.equal(upstream.length, 18);
assert.equal(classes.length, 73);
assert.equal(credits.length, 13);
const rawClasses = upstream.flatMap(cst => cst.ClassificacoesTributarias
  .filter(entry => entry.IndNfse === true).map(entry => ({ cst, entry })));
assert.equal(rawClasses.length, classes.length);
for (const row of classes) {
  const original = rawClasses.find(({ entry }) => entry.CodClassTrib === row.classificationCode);
  assert(original, `Classificação sem origem oficial: ${row.classificationCode}`);
  const { cst, entry } = original;
  for (const [field, actual] of Object.entries({ cst: cst.Cst, cstName: cst.NomeCst,
    name: entry.NomeClassTrib, shortName: entry.NomeReduzido, cstValidFrom: cst.DthIniVig,
    cstValidUntil: cst.DthFimVig, validFrom: entry.DthIniVig, validUntil: entry.DthFimVig,
    publishedAt: entry.DthPublicacao, rateType: entry.TipoAliq, legalReference: entry.TexUrlLegislacao })) {
    assert.deepEqual(row[field], actual, `Metadado divergente: ${row.classificationCode}.${field}`);
  }
  for (const [key, value] of Object.entries(row.flags)) assert.equal(value, cst[key]);
  for (const [key, value] of Object.entries(row.classificationFlags)) assert.equal(value, entry[key]);
  assert.equal(Number(row.ibsReductionPercent), Number(entry.PercRedIbs));
  assert.equal(Number(row.cbsReductionPercent), Number(entry.PercRedCbs));
}
const directory = resolve(root, 'modules/gestor/emissor-nfse/modelos/catalogs');
mkdirSync(directory, { recursive: true });
const artifacts = [];
const write = (name, value) => {
  const content = `${JSON.stringify(value, null, 2)}\n`;
  assert(content.split('\n').length - 1 <= 500, `Divida o artefato: ${name}`);
  writeFileSync(resolve(directory, name), content);
  artifacts.push({ path: name, sha256: hash(content) });
};
for (let index = 0; index < classes.length; index += 8) {
  write(`classifications-${String(index / 8 + 1).padStart(2, '0')}.json`, classes.slice(index, index + 8));
}
write('presumed-credits.json', credits);
writeFileSync(resolve(directory, 'classification-data.ts'), [
  '// Generated by scripts/generate-nfse-ibscbs-catalog.mjs from reviewed public snapshots.',
  ...artifacts.filter(file => file.path.startsWith('classifications-'))
    .map((file, index) => `import part${index + 1} from './${file.path}';`),
  '', `export default [${classes.map((_, index) => index).filter(index => index % 8 === 0)
    .map((_, index) => `...part${index + 1}`).join(', ')}];`, '',
].join('\n'));
write('provenance.json', { reviewedAt: '2026-11-10',
  classificationUrl: 'https://dfe-portal.svrs.rs.gov.br/CFF/ClassificacaoTributaria',
  classificationSourceSha256: hash(source), normalizedClassificationSha256: hash(normalized),
  creditUrl: 'https://dfe-portal.svrs.rs.gov.br/CFF/TabelaCreditoPresumido',
  creditHtmlSha256: hash(creditHtml), normalizedCreditSha256: hash(creditSource),
  cstCount: new Set(classes.map(row => row.cst)).size, classificationCount: classes.length,
  creditCount: credits.length, files: [...artifacts] });
console.log(`Catálogo oficial: ${classes.length} classificações NFS-e, ${credits.length} créditos e proveniência.`);
